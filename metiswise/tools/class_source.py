"""Export a persistent class's schema as a standalone Python module.

Only schema metadata is rendered: executable methods and ordinary class
attributes remain in the imported bases. No database writes are performed by
the exporter. Importing its output registers a class, like handwritten models.
"""

import datetime
import keyword
import math
from pathlib import Path
import sys


def _identifier(name):
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError(f"Not a Python identifier: {name!r}")
    return name


class _Source:
    def __init__(self):
        self.modules = {}

    def reference(self, value):
        module = value.__module__
        name = value.__qualname__
        for part in name.split("."):
            _identifier(part)
        for part in module.split("."):
            _identifier(part)
        target = sys.modules.get(module)
        for part in name.split("."):
            target = getattr(target, part, None)
        if target is not value or module == "__main__":
            raise ValueError(f"Cannot import {module}.{name} in a generated module")
        alias = self.modules.setdefault(module, f"_module{len(self.modules)}")
        return f"{alias}.{name}"

    def value(self, value):
        """Render supported defaults without evaluating arbitrary repr output."""
        if value is None or type(value) in (bool, int, str, bytes):
            return repr(value)
        if type(value) is float:
            return repr(value) if math.isfinite(value) else f"float({str(value)!r})"
        if isinstance(value, type):
            return self.reference(value)
        if isinstance(value, list):
            # common wraps defaults in typed_list/lazy_typed_list. Read their
            # stored values without resolving lazy links into live objects.
            return "[" + ", ".join(self.value(item) for item in list.__iter__(value)) + "]"
        if type(value) is tuple:
            items = ", ".join(self.value(item) for item in value)
            return "(" + items + ("," if len(value) == 1 else "") + ")"
        if type(value) is dict:
            return "{" + ", ".join(
                f"{self.value(key)}: {self.value(item)}" for key, item in value.items()
            ) + "}"
        if type(value) is datetime.datetime and value.tzinfo is None:
            return (
                f"{self.reference(datetime.datetime)}.fromisoformat({value.isoformat()!r})"
                f".replace(fold={value.fold})"
            )
        raise ValueError(f"Unsupported persistent default of type {type(value).__name__}")


def class_source(cls):
    """Return deterministic source for one common persistent class.

    Imports preserve all direct bases, including mixins. Only newly declared
    persistent fields are emitted; common copies inherited descriptors into
    each class, so inspecting ``__dict__`` alone is insufficient. Unsupported
    defaults and types fail explicitly rather than producing unusable source.
    """
    from common.database.DBProperties import objectlist_property, self_link_property

    name = _identifier(cls.__name__)
    source = _Source()
    bases = ", ".join(source.reference(base) for base in cls.__bases__)
    body = []
    if cls.__doc__ is not None:
        body.append(f"    {cls.__doc__!r}")

    # DBMixin declarations are reconstructed by the original mixin itself.
    mixin_fields = {
        field
        for base in cls.__bases__[1:]
        if hasattr(base, "get_persistent_attributes")
        for field in base.get_persistent_attributes()
    }
    for field in cls.get_persistent_properties():
        prop = getattr(cls, field)
        if not prop.is_new or field in mixin_fields:
            continue
        _identifier(field)
        if isinstance(prop, objectlist_property):
            raise ValueError(f"Unsupported objectlist property: {name}.{field}")
        doc = repr(prop.__doc__)
        if isinstance(prop, self_link_property):
            declaration = f"persistent({doc})"
        else:
            prop_type = prop.prop_type
            # common normalizes float to this tuple to allow integer values.
            if prop_type == (float, int):
                prop_type = float
            if prop_type is cls:
                raise ValueError(f"Unsupported explicit self reference: {name}.{field}")
            type_source = source.value(prop_type)
            default = source.value(prop.default)
            factory = "inline" if prop.is_inline else "persistent"
            declaration = f"{factory}({doc}, {type_source}, {default})"
        body.append(f"    {field} = {declaration}")

    imports = ["from common.database.DBMeta import inline, persistent"]
    imports.extend(f"import {module} as {alias}" for module, alias in source.modules.items())
    result = (
        "# Generated by MetisWISE; schema only. Regenerate instead of editing.\n\n"
        + "\n".join(imports)
        + f"\n\n\nclass {name}({bases}):\n"
        + "\n".join(body or ["    pass"])
        + "\n"
    )
    compile(result, f"{name}.py", "exec")
    return result


def write_class(cls, path=None, *, overwrite=False):
    """Write a schema module, protecting existing files by default."""
    text = class_source(cls)
    path = Path(path) if path is not None else Path("generated") / f"{cls.__name__}.py"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w" if overwrite else "x", encoding="utf-8") as stream:
        stream.write(text)
    return path
