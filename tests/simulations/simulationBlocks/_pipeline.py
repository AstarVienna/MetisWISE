#!/usr/bin/env python
"""Generate a compact, single-night dataset for the METIS EDPS workflow.

The YAML includes its own darks, flats and paired detector-linearity frames.
Automatic --doCalib generation is therefore disabled, including when a caller
supplies that option. Static calibration prototypes are generated by default.
"""

import os
from pathlib import Path
import sys

from metis_simulations import runSimulationBlock as rs


def run(dataset, argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    # Keep the explicit calibration budget even if a caller supplies --doCalib.
    # argparse uses the final occurrence of an option.
    args.append("--doCalib=0")
    if "--testRun" not in args and "-t" not in args:
        args.insert(0, "--doStatic")

    resource_root = Path(__file__).resolve().parents[1]
    yaml_root = Path(os.environ.get("MSIM_YAML_DIR", resource_root / "YAML"))
    output_root = Path(os.environ.get("MSIM_OUTDIR", "output"))
    subdir = Path(dataset)
    params = {
        "outputDir": str(output_root / subdir),
        "subDir": str(subdir),
        "doStatic": False,
        "doCalib": 0,
        "startMJD": "2027-01-25 00:00:00",
        "nCores": os.environ.get("MSIM_NCORES", "1"),
        "progID": None,
    }
    # Dry runs should not write static FITS files either.
    if "--testRun" in args or "-t" in args:
        args = [arg for arg in args if arg not in ("--doStatic", "-e")]
    rs.runSimulationBlock([str(yaml_root / f"{dataset}.yaml")], params, args)

